// Draft pull requests through the GitHub REST API. fetch is injected so tests never touch the network.
// The token goes only in the Authorization header to api.github.com; every error string is fixed, so no token or server text leaks.
import type { FetchLike, TraceEvent } from "./types.ts";

export type PrFailure = "pr_unauthorized" | "pr_forbidden" | "pr_not_found" | "pr_unprocessable" | "pr_unreachable" | "pr_failed";
export type GhResult<T> = { ok: true; value: T } | { ok: false; reason: PrFailure; error: string };
export interface GithubPrs {
  defaultBranch(slug: string): Promise<GhResult<string>>;
  openDraft(i: { slug: string; head: string; base: string; title: string; body: string }): Promise<GhResult<{ number: number; url: string }>>;
}

const API = "https://api.github.com";
const SLUG = /^[A-Za-z0-9][\w.-]*\/[\w.-]+$/;
const BRANCH = /^[\w./-]+$/;
const FAIL: Record<number, [PrFailure, string]> = {
  401: ["pr_unauthorized", "GitHub rejected the PR token (invalid or expired)"],
  403: ["pr_forbidden", "the token lacks permission for this repo (needs Contents and Pull requests: write)"],
  404: ["pr_not_found", "repo or token scope is wrong (GitHub answered 404)"],
  422: ["pr_unprocessable", "a pull request already exists or there is nothing to compare"],
};
const fail = (reason: PrFailure, error: string) => ({ ok: false as const, reason, error });
const httpFail = (status: number) => (FAIL[status] ? fail(...FAIL[status]) : fail("pr_failed", `GitHub answered HTTP ${status}`));
const unreachable = () => fail("pr_unreachable", "could not reach GitHub");

export function createGithubPrs(o: { token: string; fetch?: FetchLike; timeoutMs?: number }): GithubPrs {
  const doFetch: FetchLike = o.fetch ?? ((url, init) => fetch(url, init));
  const call = async (path: string, body?: unknown) => {
    try {
      return await doFetch(API + path, {
        method: body === undefined ? "GET" : "POST",
        headers: {
          Authorization: `Bearer ${o.token}`, Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "cloud-harness",
          ...(body === undefined ? {} : { "Content-Type": "application/json" }),
        },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
        signal: AbortSignal.timeout(o.timeoutMs ?? 15_000),
      });
    } catch { return null; } // network error or timeout; the exception text is never used
  };
  return {
    async defaultBranch(slug) {
      if (!SLUG.test(slug)) return fail("pr_failed", "invalid repo name");
      const r = await call(`/repos/${slug}`);
      if (!r) return unreachable();
      if (r.status !== 200) return httpFail(r.status);
      const b = (await r.json().catch(() => null))?.default_branch;
      return typeof b === "string" && BRANCH.test(b) ? { ok: true, value: b } : fail("pr_failed", "GitHub did not report a default branch");
    },
    async openDraft(i) {
      if (!SLUG.test(i.slug)) return fail("pr_failed", "invalid repo name");
      // draft is not a parameter: this client can only ever open drafts.
      const r = await call(`/repos/${i.slug}/pulls`, { title: i.title, head: i.head, base: i.base, body: i.body, draft: true });
      if (!r) return unreachable();
      if (r.status !== 201) return httpFail(r.status);
      const j = await r.json().catch(() => null);
      const ok = Number.isInteger(j?.number) && j.number > 0 && typeof j?.html_url === "string" && j.html_url.startsWith("https://github.com/");
      return ok ? { ok: true, value: { number: j.number, url: j.html_url } } : fail("pr_failed", "GitHub's answer did not describe a pull request");
    },
  };
}

export function describeTests(events: TraceEvent[]): string {
  const t = events.filter((e) => e.type === "test_result").at(-1);
  if (!t || t.type !== "test_result") return "not reported";
  if (t.skipped) return `not run (${t.skipped})`;
  return t.exitCode === 0 ? "passed" : `failed (exit ${t.exitCode})`;
}

export function buildPrText(o: { task: string; runId: string; model: string; tests: string }): { title: string; body: string } {
  // A fence longer than any ~ run in the task: inside it, @mentions don't notify and markdown doesn't render.
  const fence = "~".repeat(Math.max(3, ...(o.task.match(/~+/g) ?? []).map((s) => s.length + 1)));
  return {
    title: "harness: " + o.task.replace(/\s+/g, " ").trim().slice(0, 60),
    body: [`Task:`, ``, `${fence}text`, o.task, fence, ``, `- Run: \`${o.runId}\``, `- Model: \`${o.model}\``, `- Tests: ${o.tests}`, ``, `Generated by Cloud harness. Review before merging.`].join("\n"),
  };
}
