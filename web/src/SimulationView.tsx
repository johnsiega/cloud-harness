import { memo, useCallback, useState } from "react";
import { RunRail } from "./RunRail.tsx";
import { TracePanels } from "./TracePanels.tsx";
import { formatMs } from "./run-view.ts";
import { summarizeSimulation, tileElapsedMs, type SimRunState } from "./simulation-view.ts";
import { useSimulation } from "./useSimulation.ts";

const Tile = memo(function Tile({ id, index, run, selected, onSelect }: { id: string; index: number; run: SimRunState; selected: boolean; onSelect: (id: string) => void }) {
  const { phase, startupMs } = run.view;
  return (
    <button type="button" className={`tile ${phase}${selected ? " selected" : ""}`} onClick={() => onSelect(id)} aria-pressed={selected} aria-label={`Simulated run ${index + 1}: ${phase}`}>
      <span className="n">{index + 1}</span>
      <span className="ph">{phase}</span>
      <span className="m">{formatMs(startupMs)} · {formatMs(tileElapsedMs(run))}</span>
    </button>
  );
});

export function SimulationView() {
  const { state, meta, start } = useSimulation();
  const [n, setN] = useState(100);
  const [selected, setSelected] = useState<string | undefined>();
  const select = useCallback((id: string) => setSelected(id), []);
  const sum = summarizeSimulation(state);
  const busy = meta.starting || meta.streaming;
  const chosen = selected ? state.runs[selected] : undefined;

  return (
    <>
      <p className="banner" role="note"><strong>Simulated:</strong> no MicroVMs are started. These runs are generated by the control plane to test the UI at scale.</p>
      <form className="simform" onSubmit={(e) => { e.preventDefault(); setSelected(undefined); void start(n); }}>
        <label>Runs <input type="number" min={1} max={200} value={n} onChange={(e) => setN(Number(e.target.value))} disabled={busy} /></label>
        <button type="submit" className="run" disabled={busy}>{busy ? "Simulating…" : "Start simulation"}</button>
        <p className="simsum" role="status" aria-live="polite">
          <span><b>{sum.total}</b> started</span>
          <span><b data-testid="running">{sum.running}</b> in progress</span>
          <span><b>{sum.done}</b> done</span>
          <span><b>{sum.error}</b> failed</span>
          <span>median startup <b>{formatMs(sum.medianStartupMs)}</b></span>
        </p>
      </form>
      {meta.error && <p className="note error" role="alert">{meta.error}</p>}
      <div className="grid" role="group" aria-label="Simulated runs">
        {state.order.map((id, i) => <Tile key={id} id={id} index={i} run={state.runs[id]} selected={id === selected} onSelect={select} />)}
      </div>
      {chosen && (
        <>
          <h2 className="simhead">Simulated run {state.order.indexOf(selected!) + 1}</h2>
          <RunRail view={chosen.view} />
          <TracePanels view={chosen.view} />
        </>
      )}
    </>
  );
}
